create table if not exists public.restaurant_dish_availability (
  id bigint generated by default as identity primary key,
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  dish_id bigint not null references public.dish_catalog(id) on delete cascade,
  price integer not null check (price > 0),
  is_available boolean not null default false,
  menu_type text not null default 'everyday' check (menu_type in ('everyday','special')),
  updated_at timestamptz not null default now(),
  unique (restaurant_id, dish_id)
);

create table if not exists public.dish_preorder_requests (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete cascade,
  dish_id bigint references public.dish_catalog(id) on delete set null,
  dish_name text not null,
  quantity integer not null default 1 check (quantity between 1 and 50),
  requested_for timestamptz,
  notes text not null default '',
  delivery_area text not null default '',
  status text not null default 'pending' check (status in ('pending','accepted','cancelled')),
  accepted_restaurant_id uuid references public.restaurants(id) on delete set null,
  accepted_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.dish_catalog enable row level security;
alter table public.restaurant_dish_availability enable row level security;
alter table public.dish_preorder_requests enable row level security;

drop policy if exists "Anyone can read active dish catalogue" on public.dish_catalog;
create policy "Anyone can read active dish catalogue" on public.dish_catalog for select to anon, authenticated using (is_active = true);
drop policy if exists "Approved restaurants read dish availability" on public.restaurant_dish_availability;
create policy "Approved restaurants read dish availability" on public.restaurant_dish_availability for select to authenticated using (exists (select 1 from public.restaurants r where r.id = restaurant_id and r.owner_id = (select auth.uid()) and r.status = 'approved'));
drop policy if exists "Customers read available dishes" on public.restaurant_dish_availability;
create policy "Customers read available dishes" on public.restaurant_dish_availability for select to anon, authenticated using (is_available = true and exists (select 1 from public.restaurants r where r.id = restaurant_id and r.status = 'approved'));
drop policy if exists "Approved restaurants manage own dish availability" on public.restaurant_dish_availability;
create policy "Approved restaurants manage own dish availability" on public.restaurant_dish_availability for all to authenticated using (exists (select 1 from public.restaurants r where r.id = restaurant_id and r.owner_id = (select auth.uid()) and r.status = 'approved')) with check (exists (select 1 from public.restaurants r where r.id = restaurant_id and r.owner_id = (select auth.uid()) and r.status = 'approved'));
drop policy if exists "Customers create own pre-order requests" on public.dish_preorder_requests;
create policy "Customers create own pre-order requests" on public.dish_preorder_requests for insert to authenticated with check (customer_id = (select auth.uid()) and exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.account_type = 'customer'));
drop policy if exists "Customers read own pre-order requests" on public.dish_preorder_requests;
create policy "Customers read own pre-order requests" on public.dish_preorder_requests for select to authenticated using (customer_id = (select auth.uid()));
drop policy if exists "Approved restaurants see pending pre-order requests" on public.dish_preorder_requests;
create policy "Approved restaurants see pending pre-order requests" on public.dish_preorder_requests for select to authenticated using (status = 'pending' and exists (select 1 from public.restaurants r where r.owner_id = (select auth.uid()) and r.status = 'approved'));

create or replace function public.accept_dish_preorder_request(p_request_id uuid)
returns table (request_id uuid, accepted boolean, accepted_restaurant_id uuid)
language plpgsql security definer set search_path = ''
as $$
declare v_restaurant_id uuid; v_status text;
begin
  select r.id into v_restaurant_id from public.restaurants r
  where r.owner_id = (select auth.uid()) and r.status = 'approved' limit 1;
  if v_restaurant_id is null then raise exception 'An approved restaurant account is required.'; end if;
  update public.dish_preorder_requests d
  set status = 'accepted', accepted_restaurant_id = v_restaurant_id, accepted_at = now()
  where d.id = p_request_id and d.status = 'pending'
  returning d.status into v_status;
  if v_status = 'accepted' then return query select p_request_id, true, v_restaurant_id;
  else return query select p_request_id, false, null::uuid; end if;
end;
$$;
revoke all on function public.accept_dish_preorder_request(uuid) from public, anon;
grant execute on function public.accept_dish_preorder_request(uuid) to authenticated;
grant select on public.dish_catalog to anon, authenticated;
grant select, insert, update, delete on public.restaurant_dish_availability to authenticated;
grant select, insert on public.dish_preorder_requests to authenticated;
grant usage, select on sequence public.dish_catalog_id_seq to anon, authenticated;
grant usage, select on sequence public.restaurant_dish_availability_id_seq to authenticated;
