  id bigint generated by default as identity primary key,
  delivery_area text not null,
  restaurant_stop_count integer not null check (restaurant_stop_count between 1 and 20),
  delivery_plan text not null check (delivery_plan in ('shared_courier', 'separate_couriers')),
  fee integer not null check (fee >= 0),
  active boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (delivery_area, restaurant_stop_count, delivery_plan)
);

create table if not exists public.restaurant_payment_accounts (
  restaurant_id uuid primary key references public.restaurants(id) on delete cascade,
  provider text not null default 'paystack' check (provider = 'paystack'),
  subaccount_code text unique,
  verified_at timestamptz,
  enabled boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.payment_allocations (
  id uuid primary key default gen_random_uuid(),
  checkout_session_id uuid not null references public.checkout_sessions(id) on delete restrict,
  order_id bigint references public.orders(id) on delete restrict,
  restaurant_id uuid references public.restaurants(id) on delete restrict,
  allocation_type text not null check (allocation_type in ('restaurant_net', 'platform_commission', 'delivery_fee', 'gateway_fee', 'refund')),
  amount integer not null check (amount >= 0),
  commission_amount integer not null default 0 check (commission_amount >= 0),
  currency text not null default 'NGN' check (currency = 'NGN'),
  settlement_status text not null default 'pending'
    check (settlement_status in ('pending', 'ready', 'transferred', 'failed', 'reversed', 'not_applicable')),
  provider_transfer_reference text unique,
  created_at timestamptz not null default now(),
  check (
    (allocation_type in ('restaurant_net', 'platform_commission') and order_id is not null and restaurant_id is not null)
    or (allocation_type in ('delivery_fee', 'gateway_fee', 'refund'))
  )
);

create index if not exists payment_allocations_checkout_idx on public.payment_allocations(checkout_session_id);
create index if not exists payment_allocations_restaurant_status_idx on public.payment_allocations(restaurant_id, settlement_status);

create table if not exists public.payment_events (
  id bigint generated by default as identity primary key,
  provider text not null default 'paystack' check (provider = 'paystack'),
  provider_event_id text,
  payment_reference text not null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  processed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (provider, provider_event_id)
);

create index if not exists payment_events_reference_idx on public.payment_events(payment_reference);

create table if not exists public.menu_item_reviews (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete restrict,
  order_item_id bigint not null unique references public.order_items(id) on delete restrict,
  customer_id uuid not null references auth.users(id) on delete restrict,
  restaurant_id uuid not null references public.restaurants(id) on delete restrict,
  menu_item_id bigint references public.menu_items(id) on delete restrict,
  rating integer not null check (rating between 1 and 5),
  review_text text not null default '' check (char_length(review_text) <= 1000),
  is_public boolean not null default true,
  created_at timestamptz not null default now(),
  check ((menu_item_id is not null and is_public) or (menu_item_id is null and not is_public))
);

create index if not exists menu_item_reviews_item_created_idx on public.menu_item_reviews(menu_item_id, created_at desc) where is_public;
create index if not exists menu_item_reviews_customer_idx on public.menu_item_reviews(customer_id, created_at desc);
