drop function if exists public.get_public_available_menu();
create function public.get_public_available_menu()
returns table(
  id bigint,
  name text,
  category text,
  price integer,
  rating numeric,
  tag text,
  menu_type text,
  description text,
  image_url text,
  sort_order integer,
  restaurant_name text,
  rating_count bigint
)
language sql
stable
security definer
set search_path = ''
as $function$
  select
    m.id,
    m.name,
    m.category,
    m.price,
    coalesce(ratings.rating, 0::numeric) as rating,
    m.tag,
    m.menu_type,
    m.description,
    m.image_url,
    m.sort_order,
    r.name as restaurant_name,
    coalesce(ratings.rating_count, 0::bigint) as rating_count
  from public.menu_items m
  join public.restaurants r on r.id = m.restaurant_id
  left join lateral (
    select
      round(avg(rr.rating)::numeric, 1) as rating,
      count(rr.id)::bigint as rating_count
    from public.menu_item_reviews rr
    where rr.menu_item_id = m.id and rr.is_public
  ) ratings on true
  where m.is_available = true
    and r.status = 'approved'
  order by m.menu_type asc, m.sort_order asc;
$function$;

revoke all on function public.get_public_available_menu() from public;
grant execute on function public.get_public_available_menu() to anon, authenticated;

