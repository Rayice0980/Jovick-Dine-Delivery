create or replace function public.submit_menu_item_review(
  p_order_item_id bigint,
  p_rating integer,
  p_review_text text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_customer_id uuid := auth.uid();
  v_order_id bigint;
  v_order_status text;
  v_restaurant_id uuid;
  v_menu_item_id bigint;
  v_item_name text;
  v_is_preorder boolean;
  v_average numeric;
  v_count bigint;
begin
  if v_customer_id is null then
    raise exception 'Please sign in to review your food.';
  end if;
  if p_rating is null or p_rating < 1 or p_rating > 5 then
    raise exception 'Choose a rating from 1 to 5 stars.';
  end if;
  if char_length(coalesce(p_review_text, '')) > 1000 then
    raise exception 'Your review must be 1,000 characters or fewer.';
  end if;

  select oi.order_id, o.status, oi.restaurant_id, oi.menu_item_id, oi.item_name,
         (oi.preorder_request_id is not null)
    into v_order_id, v_order_status, v_restaurant_id, v_menu_item_id, v_item_name, v_is_preorder
  from public.order_items oi
  join public.orders o on o.id = oi.order_id
  where oi.id = p_order_item_id and o.customer_id = v_customer_id
  for update of o;

  if not found then
    raise exception 'This food item does not belong to one of your orders.';
  end if;
  if v_order_status <> 'delivered' then
    raise exception 'You can review food after the restaurant marks the order delivered.';
  end if;
  if v_restaurant_id is null then
    raise exception 'The restaurant for this food item could not be identified.';
  end if;

  update public.orders
    set customer_received_at = coalesce(customer_received_at, now())
  where id = v_order_id and customer_id = v_customer_id;

  insert into public.menu_item_reviews(
    order_id, order_item_id, customer_id, restaurant_id, menu_item_id,
    rating, review_text, is_public
  )
  values (
    v_order_id, p_order_item_id, v_customer_id, v_restaurant_id, v_menu_item_id,
    p_rating, trim(coalesce(p_review_text, '')), not v_is_preorder and v_menu_item_id is not null
  );

  if v_menu_item_id is not null and not v_is_preorder then
    select round(avg(r.rating)::numeric, 1), count(*)::bigint
      into v_average, v_count
    from public.menu_item_reviews r
    where r.menu_item_id = v_menu_item_id and r.is_public;

    update public.menu_items
      set rating = coalesce(v_average, 0)
      where id = v_menu_item_id;
  else
    v_average := null;
    v_count := 0;
  end if;

  return jsonb_build_object(
    'success', true,
    'order_item_id', p_order_item_id,
    'menu_item_id', v_menu_item_id,
    'item_name', v_item_name,
    'rating', p_rating,
    'average_rating', v_average,
    'rating_count', v_count,
    'public_review', (not v_is_preorder and v_menu_item_id is not null)
  );
exception
  when unique_violation then
    raise exception 'You have already reviewed this food item from this order.';
end;
$$;

revoke all on function public.submit_menu_item_review(bigint, integer, text) from public, anon;
grant execute on function public.submit_menu_item_review(bigint, integer, text) to authenticated;

