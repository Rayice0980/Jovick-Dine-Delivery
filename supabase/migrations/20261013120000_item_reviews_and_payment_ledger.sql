    check (payment_status in ('unpaid', 'pending', 'paid', 'failed', 'refunded', 'cash_due', 'cash_collected'));

create table if not exists public.checkout_sessions (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete restrict,
  status text not null default 'pending_payment'
    check (status in ('pending_payment', 'paid', 'payment_failed', 'cancelled', 'partially_refunded', 'refunded', 'cash_due', 'cash_collected')),
  payment_method text not null check (payment_method in ('paystack', 'cash_on_delivery')),
  currency text not null default 'NGN' check (currency = 'NGN'),
  food_subtotal integer not null check (food_subtotal > 0),
  delivery_fee integer not null default 0 check (delivery_fee >= 0),
  total integer not null check (total = food_subtotal + delivery_fee),
  commission_rate numeric(5,4) not null default 0.1000 check (commission_rate = 0.1000),
  delivery_area text not null,
  delivery_plan text not null check (delivery_plan in ('shared_courier', 'separate_couriers')),
  restaurant_stop_count integer not null check (restaurant_stop_count between 1 and 20),
  customer_name text not null,
  customer_phone text not null,
  customer_email text not null,
  delivery_address text not null,
  delivery_notes text not null default '',
  requested_for timestamptz,
  cart_items jsonb not null check (jsonb_typeof(cart_items) = 'array'),
  finalized_at timestamptz,
  payment_reference text unique,
  provider_transaction_id text unique,
  provider_fee_kobo bigint not null default 0 check (provider_fee_kobo >= 0),
  automatic_split boolean not null default false,
  idempotency_key uuid not null,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer_id, idempotency_key)
);

