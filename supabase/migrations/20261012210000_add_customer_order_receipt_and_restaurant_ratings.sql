create table if not exists public.restaurant_ratings (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  customer_id uuid not null references auth.users(id) on delete cascade,
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  created_at timestamptz not null default now()
);
alter table public.restaurant_ratings enable row level security;
revoke all on public.restaurant_ratings from anon, authenticated;
grant select on public.restaurant_ratings to authenticated;
drop policy if exists "Customers can read their own restaurant ratings" on public.restaurant_ratings;
create policy "Customers can read their own restaurant ratings"
on public.restaurant_ratings for select to authenticated
using (customer_id = (select auth.uid()));
create or replace function public.submit_restaurant_rating(p_order_id bigint, p_rating integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_customer_id uuid := auth.uid();
  v_restaurant_id uuid;
  v_restaurant_count integer;
  v_status text;
  v_existing integer;
  v_average numeric;
begin
  if v_customer_id is null then raise exception 'Please sign in to rate this restaurant.'; end if;
  if p_rating is null or p_rating < 1 or p_rating > 5 then raise exception 'Choose a rating from 1 to 5 stars.'; end if;
  select o.status into v_status from public.orders o where o.id = p_order_id and o.customer_id = v_customer_id;
  if not found then raise exception 'This order does not belong to your account.'; end if;
  if v_status <> 'delivered' then raise exception 'You can confirm receipt and rate the restaurant after the order is marked delivered.'; end if;
  select count(distinct oi.restaurant_id), (array_agg(distinct oi.restaurant_id))[1]
    into v_restaurant_count, v_restaurant_id from public.order_items oi where oi.order_id = p_order_id;
  if v_restaurant_count <> 1 or v_restaurant_id is null then raise exception 'We could not identify one restaurant for this order.'; end if;
  select rr.rating into v_existing from public.restaurant_ratings rr where rr.order_id = p_order_id;
  if v_existing is not null then raise exception 'You have already rated this order.'; end if;
  insert into public.restaurant_ratings(order_id, customer_id, restaurant_id, rating) values (p_order_id, v_customer_id, v_restaurant_id, p_rating);
  select round(avg(rr.rating)::numeric, 1) into v_average from public.restaurant_ratings rr where rr.restaurant_id = v_restaurant_id;
  update public.menu_items set rating = v_average where restaurant_id = v_restaurant_id;
  return jsonb_build_object('success', true, 'restaurant_id', v_restaurant_id, 'rating', p_rating, 'restaurant_average', v_average);
end;
$$;
revoke all on function public.submit_restaurant_rating(bigint, integer) from public, anon;
grant execute on function public.submit_restaurant_rating(bigint, integer) to authenticated;